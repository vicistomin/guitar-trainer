export function getChordsByCategory(category) {
  return chords.filter(c => c.category === category);
}

export function getChordById(id) {
  return chords.find(c => c.id === id);
}

export function getChordsForInstrument(instrumentId, tuningId) {
  return chords.filter(c => c.instrument === instrumentId && c.tuning === tuningId);
}
